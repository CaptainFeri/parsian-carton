# -*- coding: utf-8 -*-
"""ساخت فایل اکسل نمونه برای آزمون خوانندهٔ صفحه‌گسترده."""
import sys
from openpyxl import Workbook

out = sys.argv[1]
wb = Workbook()

ws = wb.active
ws.title = "محصولات"

# دو سطر عنوان/خالی پیش از سرستون‌ها — خواننده باید از آن‌ها بگذرد.
ws.append(["فهرست محصولات پارسیان کارتن"])
ws.append([])
ws.append(["کد محصول", "نام محصول", "دسته‌بندی", "قیمت", "قیمت حراج",
           "موجودی", "تصویر", "ویژگی: سایز", "توضیح کوتاه"])
ws.append(["PC-01", "کارتن پستی سایز ۱", "کارتن پستی", 8500, "", 120,
           "postal-1.svg", "سایز ۱", "کارتن پستی سه لایه"])
# سلول میانی خالی (ستون «قیمت حراج» و «تصویر» جا افتاده‌اند).
ws.append(["PC-02", "کارتن پستی سایز ۲", "کارتن پستی", 9700, 8900, 0,
           None, "سایز ۲", None])
# عدد به‌صورت متن و ارقام فارسی.
ws.append(["PC-03", "کارتن اسباب‌کشی بزرگ", "کارتن اسباب‌کشی>۵ لایه", "۴۵٬۰۰۰", "", "۳۰",
           "https://parsiancarton.com/img/moving-l.jpg", "بزرگ", "مقاوم"])
# سطر کاملاً خالی — باید نادیده گرفته شود.
ws.append([])
# فرمول: openpyxl مقدار محاسبه‌شده ندارد، پس فقط متن فرمول ذخیره می‌شود.
ws.append(["PC-04", "پاکت حبابدار", "پاکت حبابدار", 3200, "", 500,
           "bubble.svg", "متوسط", "ضدضربه"])

ws2 = wb.create_sheet("راهنما")
ws2.append(["این برگه نباید خوانده شود"])
ws2.append(["ستون الف", "ستون ب"])

wb.save(out)
print("نوشته شد:", out)
